"""Builds i18n-zh.js (window.YogaI18nZh) from zh/part*.py, keyed by the English sources so nothing drifts."""
import json, re, subprocess, sys, pathlib
here = pathlib.Path(__file__).parent; root = here.parent
ns = {}
for p in ["part1.py", "part2.py", "part3.py"]: exec((here / p).read_text(), ns)
src = json.loads(subprocess.check_output(["node", "-e", """
const I=require('./i18n.js'); const {POSES}=require('./poses.js'); const P=require('./profile.js');
console.log(JSON.stringify({hints:Object.keys(I.HINTS_DE), props:Object.keys(I.PROPS_DE), ids:POSES.map(p=>p.id), learn:Object.keys(I.LEARN),
 blocks:Object.keys(I.BLOCKS_DE), sections:Object.keys(I.SECTIONS_DE), tags:Object.keys(I.TAGS_EN), offers:Object.keys(I.OFFERS_DE),
 learnLen:Object.fromEntries(Object.entries(I.LEARN).map(([k,v])=>[k,v.en.how.length])), breath:Object.fromEntries(Object.entries(I.BREATH).map(([k,v])=>[k,Array.isArray(v.en)?v.en.length:-1])), basics:I.BASICS.en.length,
 natures:P.NATURES.map(n=>n.id), animals:P.ANIMALS.map(a=>a.id), themes:P.THEMES.map(t=>t.id), care:P.CARE.map(c=>c.id)}))"""], cwd=root))
t = (root / "player.template.html").read_text()
def objkeys(name):
    s = t.index("const %s = {" % name); e = t.index("\n  };", s)
    return [k for k, v in re.findall(r'"((?:[^"\\]|\\.)*)":\s*"((?:[^"\\]|\\.)*)"', t[s:e])]
ui, attr = objkeys("UI_DE"), objkeys("ATTR_DE")
err = []
def same(a, b, what):
    if len(a) != len(b): err.append(f"{what}: {len(a)} vs {len(b)}")
same(ns["HINTS"], src["hints"], "hints"); same(ns["PROPS"], src["props"], "props"); same(ns["UI"], ui, "ui"); same(ns["ATTR"], attr, "attr")
for what, d, keys in [("names", ns["NAMES"], src["ids"]), ("cues", ns["CUES"], src["ids"]), ("learn", ns["LEARN"], src["learn"]), ("blocks", ns["BLOCKS"], src["blocks"]),
                      ("sections", ns["SECTIONS"], src["sections"]), ("tags", ns["TAGS"], src["tags"]), ("offers", ns["OFFERS"], src["offers"]),
                      ("natures", ns["NATURES"], src["natures"]), ("animals", ns["ANIMALS"], src["animals"]), ("care", ns["CARE"], src["care"])]:
    miss = [k for k in keys if k not in d]; extra = [k for k in d if k not in keys]
    if miss or extra: err.append(f"{what}: missing {miss[:8]} extra {extra[:8]}")
for k, n in src["learnLen"].items():
    if k in ns["LEARN"] and len(ns["LEARN"][k]["how"]) != n: err.append(f"learn {k} how len")
for k, n in src["breath"].items():
    v = ns["BREATH"].get(k)
    if v is None or (n >= 0 and len(v) != n): err.append(f"breath {k}")
for h_en, h_zh in zip(src["hints"], ns["HINTS"]):
    for ph in ["{side}", "{other}"]:
        if h_en.count(ph) != h_zh.count(ph): err.append(f"placeholder {ph}: {h_en!r} -> {h_zh!r}")
if err: print("\n".join(err)); sys.exit(1)
data = dict(HINTS=dict(zip(src["hints"], ns["HINTS"])), PROPS=dict(zip(src["props"], ns["PROPS"])), UI=dict(zip(ui, ns["UI"])), ATTR=dict(zip(attr, ns["ATTR"])),
            NAMES=ns["NAMES"], CUES=ns["CUES"], LEARN=ns["LEARN"], BASICS=ns["BASICS"], BREATH=ns["BREATH"], BLOCKS=ns["BLOCKS"], SECTIONS=ns["SECTIONS"], PEAK=ns["PEAK"],
            TAGS=ns["TAGS"], OFFERS=ns["OFFERS"], T=ns["T"], LEVEL=ns["LEVEL"], QS=ns["QS"], NATURES=ns["NATURES"], ANIMALS=ns["ANIMALS"], AGES=ns["AGES"], TEMPOS=ns["TEMPOS"],
            THEMES=ns["THEMES"], LEVELS=ns["LEVELS"], TEMPO_CFG=ns["TEMPO_CFG"], CARE=ns["CARE"], STORY=ns["STORY"], TIPS=ns["TIPS"], WHY_GT=ns["WHY_GT"])
js = ("// Simplified Chinese (zh-Hans). Generated by zh/make_zh.py from zh/part*.py; keyed by the English sources.\n"
      "(function (root) {\n  root.YogaI18nZh = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "  if (typeof module !== \"undefined\") module.exports = root.YogaI18nZh;\n"
      "})(typeof window !== \"undefined\" ? window : globalThis);\n")
(root / "i18n-zh.js").write_text(js, encoding="utf-8")
print("i18n-zh.js", len(js.encode()) // 1024, "KB,", sum(len(v) if isinstance(v, (dict, list)) else 1 for v in data.values()), "entries")
