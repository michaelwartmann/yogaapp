  function flip(w) { return w.replace(/^([Rr])echt/, (m, r) => (r === "R" ? "Link" : "link")); }
  function hint(template, side, lang) {
    side = side === "left" ? "left" : "right";
    const other = side === "right" ? "left" : "right";
    if (lang === "de" && HINTS_DE[template]) {
      return HINTS_DE[template]
        .replace(/\{S:([A-Za-zäöü]+)\}/g, (m, w) => (side === "right" ? w : flip(w)))
        .replace(/\{O:([A-Za-zäöü]+)\}/g, (m, w) => (side === "right" ? flip(w) : w));
    }
    const out = template.replace(/\{side\}/g, side).replace(/\{other\}/g, other);
    return out[0].toUpperCase() + out.slice(1);
  }
